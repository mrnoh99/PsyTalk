· 방 목록 상단 「관리자모드」/「가입승인」 배너로 진입

문의·버그 제안: BugReport 방 또는 전체관리자에게 연락해 주세요.$guide$;
BEGIN
  SELECT id INTO v_sender
  FROM public.profiles
  WHERE role = 'superadmin'
  ORDER BY id
  LIMIT 1;

  IF v_sender IS NULL THEN
    RAISE EXCEPTION 'superadmin 프로필이 없습니다. protect_superadmin.sql 실행 후 다시 시도하세요.';
  END IF;

  INSERT INTO public.messages (id, room_id, sender_id, content, type, created_at)
  VALUES (v_msg, v_room, v_sender, v_content, 'text', now())
  ON CONFLICT (id) DO UPDATE SET
    content    = EXCLUDED.content,
    created_at = now();

  RAISE NOTICE '전체공지에 사용법 게시 완료 (message_id=%)', v_msg;
END $$;

