-- ─────────────────────────────────────────────────────────────────────────
-- [1] 현황 확인 — 먼저 이 SELECT 만 실행해서 어떤 방이 있는지 보세요.
--     (방 id·이름·종류·정렬순서 + 멤버수·메시지수)
-- ─────────────────────────────────────────────────────────────────────────
SELECT r.id, r.name, r.category, r.sort_order, r.created_by,
       (SELECT count(*) FROM public.room_members m WHERE m.room_id = r.id) AS members,
       (SELECT count(*) FROM public.messages    g WHERE g.room_id = r.id) AS messages
FROM public.rooms r
ORDER BY r.category, r.name, r.sort_order;


-- ─────────────────────────────────────────────────────────────────────────
-- [2] 같은 이름의 중복 방 정리 — 이름이 같은 방은 1개만 남기고 삭제.
--     · 기본 방(전체공지/학술활동)은 시드의 고정 id 를 우선 보존
--     · 그 외에는 sort_order 가 작은(먼저 만든) 방을 보존
--     ※ 이름이 서로 다른 테스트 방은 여기서 안 지워집니다 → [3] 또는 [4] 사용
-- ─────────────────────────────────────────────────────────────────────────
WITH ranked AS (
  SELECT id,
         row_number() OVER (
           PARTITION BY name
           ORDER BY
             (id IN ('11111111-1111-1111-1111-111111110001',
                     '11111111-1111-1111-1111-111111110012')) DESC,  -- 기본 방 우선 보존
             sort_order ASC,
             id ASC
         ) AS rn
  FROM public.rooms
)
DELETE FROM public.rooms
WHERE id IN (SELECT id FROM ranked WHERE rn > 1);


